"""Write experiment results as JSON and as LaTeX fragments the slides \\input."""
from __future__ import annotations

import json
from pathlib import Path

_TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
        "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


class Raw(str):
    """A cell that is already LaTeX and must not be escaped."""


def esc(value) -> str:
    if isinstance(value, Raw):
        return str(value)
    return "".join(_TEX.get(ch, ch) for ch in str(value))


def code(value) -> Raw:
    return Raw(r"\texttt{" + esc(value) + "}")


def mark(ok: bool | None) -> Raw:
    return Raw({True: r"\cmark", False: r"\xmark", None: r"\pmark"}[ok])


def tabular(header: list, rows: list[list], colspec: str, size: str = r"\scriptsize") -> str:
    colspec = colspec.replace("p{", r">{\raggedright\arraybackslash}p{")
    lines = [rf"{{{size}\setlength{{\tabcolsep}}{{3pt}}", rf"\begin{{tabular}}{{{colspec}}}", r"\toprule",
             " & ".join(rf"\textbf{{{esc(h)}}}" if not isinstance(h, Raw) else h for h in header) + r" \\",
             r"\midrule"]
    lines += [" & ".join(esc(c) for c in row) + r" \\" for row in rows]
    lines += [r"\bottomrule", r"\end{tabular}}"]
    return "\n".join(lines) + "\n"


def verbatim_lines(lines: list[str], size: str = r"\scriptsize") -> str:
    body = "\n".join(lines)
    return f"{{{size}\n\\begin{{verbatim}}\n{body}\n\\end{{verbatim}}}}\n"


class Results:
    """Collects outputs for one workshop's ``results/`` directory."""

    def __init__(self, experiment_file: str):
        self.dir = Path(experiment_file).resolve().parents[1] / "results"
        self.dir.mkdir(exist_ok=True)

    def json(self, name: str, data) -> None:
        (self.dir / f"{name}.json").write_text(json.dumps(data, indent=2, default=str) + "\n", encoding="utf-8")

    def tex(self, name: str, text: str) -> None:
        (self.dir / f"{name}.tex").write_text(f"% generated by agentsim; do not edit\n{text}", encoding="utf-8")
